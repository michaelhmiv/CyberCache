-- 0071: Vendor drops Scrap + scrap meters (economy redesign brief
-- S6 + S4.4; owner ruling 6, 2026-11-03: the vendor drops the base
-- material; the lever era gets its scrap dashboard).
--
-- What lands here:
--   1. cc_vendor_catalog restated VERBATIM from 0069 with ONE row
--      removed: the Scrap material row (10 cr). The one VALUES list feeds
--      cc_vendor_price / cc_vendor_buy / cc_vendor_sell, so the
--      single removal ends the Scrap sale line, removes Scrap from
--      the daily rotation's material slot pool (the rotation now
--      deals among BallisticParts / ReactiveComponents /
--      TechFragments / VoidDust + the five essences), and removes
--      the buyback anchor — with no vendor value there is nothing
--      for vendorBuybackRate to multiply, so the vendor neither
--      buys nor sells the engine material. The 9 consumable staples
--      and the other four materials keep their rows untouched.
--      The TS twin is VENDOR_MATERIALS in src/lib/vendor/catalog.ts
--      (the row is deleted there in the same change; parity is
--      pinned by src/test/vendorRotation.test.ts).
--   2. Scrap meters: nine columns on economy_metrics and
--      cc_compute_economy_metrics restated VERBATIM from 0068 with
--      the scrap folds added — minted breakouts (salvage incl. the
--      boss Second Opinion auto-scrap, roaming incl. offline
--      settlement, dispatch, endless, starter bundle), the
--      destroyed-by-crafting breakout (the materials fold's Scrap
--      leg plus tint escrows, net of cancel refunds; reforge and
--      contract-reroll destruction already had columns), and the
--      totals + net_scrap_change — the daily report's first net
--      scrap line. Every fold reads the verified-action ledger the
--      flows already write; no flow's payload or behavior changes.
--      Market trades move Scrap between players and burn none of
--      it (the fee is credits-side), so the market is net-zero for
--      scrap by construction and carries no breakout. The InMemory
--      economy twin folds identically.
--
-- The TS twins land in the same change: src/lib/vendor/catalog.ts
-- (row removal), src/server/economy/store.ts + memory.ts (the new
-- meter fields + folds), docs/ECONOMY.md (the meter table), pinned
-- by src/test/vendorRotation.test.ts,
-- src/test/economyObservability.test.ts, and
-- src/test/econ6ScrapMeters.test.ts.

