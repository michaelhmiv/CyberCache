-- =====================================================================
-- 0037 — Cache box release lane: 1 free box daily + watch-ad boxes
-- to a 10/day total cap (content owner: src/content/cacheLane.ts).
--
-- CACHE BOX ≠ LOOT DROP (Michael's monetization law): drops are
-- earned gameplay; cache boxes are the ad lane. This migration
-- rebuilds the box economy around a DAILY BUDGET:
--
--   * ONE budget: 10 openings per UTC day per account (the
--     cacheBoxDailyCap lever, default 10, clamp [1, 30]), counting
--     EVERY opening of the day, the free one included.
--   * The day's FIRST opening is FREE — no key, no ad — and the
--     server resolves it as free even when the caller asked to pay
--     (free-first ordering: the free slot can never be wasted).
--   * Openings 2..cap are paid per opening, player's choice: 1
--     cache key OR one watch-ad attestation. The attestation is
--     client-attested — the cc_make_item call itself, carrying the
--     ad unit id — with NO server-side verification (SSV); the
--     hard daily cap is the abuse control, and the nonce ledger
--     makes each opening exactly-once (replays grant nothing).
--   * Keys stay a stock (fragments, leaderboard 0035, streak 0036)
--     that buys ad-free openings INSIDE the budget. They never buy
--     an opening past the cap — the same rule the approved
--     slot-machine defaults state for key prizes.
--
-- Pieces:
--   1. cache_box_openings — one row per opening (player, UTC day,
--      resolved payment, ad unit id for ad openings, minted item):
--      the budget's counter + audit record, written inside
--      cc_make_item's transaction.
--   2. cc_make_item restated (0031 body + the budget gate, payment
--      resolution, key spend only for key openings, the opening
--      row, and 'payment' + 'cache_lane' on the result). The draw
--      is untouched: cc_draw_odds('cache_primary_rarity',
--      cache_quality) with the 0031 quality computation — chest
--      odds stay Rare 60 / Epic 32 / Legendary 8 (weights
--      6000/3200/800, seeded in 0004, not touched here) and Cache
--      Rank's cacheQuality wiring is byte-identical.
--   3. cc_claim_rewarded_cache_key DROPPED — the old 3-keys/day +
--      5-minute-cooldown rewarded claim is retired. Ads no longer
--      mint keys. The ad_reward_grants table stays (historical
--      rows; the cache_keys_from_ads meter folds pre-0037 ledger
--      rows and simply sees no new ones).
--   4. Economy meters: economy_metrics gains cache_boxes_opened_
--      free / _ad / _key — the lane's issuance by payment, folded
--      from cc_make_item ledger rows (rows written before 0037
--      carry no 'payment' and count as key — every pre-lane
--      opening was key-paid). cc_compute_economy_metrics restated
--      (0036 body + the three folds). cache_opens is unchanged.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Openings: the budget's record (one row per box opened).
-- ---------------------------------------------------------------------
create table if not exists public.cache_box_openings (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null references public.profiles(id) on delete cascade,
  open_day date not null,
  payment text not null check (payment in ('free', 'ad', 'key')),
  ad_unit_id text,
  item_id uuid references public.item_instances(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists cache_box_openings_player_day_idx
  on public.cache_box_openings (player_id, open_day);

-- ---------------------------------------------------------------------
-- 2. cc_make_item restated (0031 body + the cache lane). The old
--    two-argument signature is dropped first so no overload keeps
--    the pre-lane, budget-free draw alive; the rewarded-key claim
--    is dropped outright (retired lane).
-- ---------------------------------------------------------------------
drop function if exists public.cc_make_item(uuid, text);
drop function if exists public.cc_claim_rewarded_cache_key(uuid, text, text, text);

CREATE OR REPLACE FUNCTION public.cc_make_item(p_player_id uuid, nonce text, p_payment text DEFAULT 'key', p_ad_unit_id text DEFAULT NULL)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  actor uuid := p_player_id;
  prior jsonb;
  p public.profiles%rowtype;
  item public.item_instances%rowtype;
  result jsonb;
  odds jsonb;
  v_open_day date := (now() at time zone 'utc')::date;
  v_daily_cap integer := 10;
  v_opened_today integer := 0;
  v_free_today integer := 0;
  v_ad_today integer := 0;
  v_key_today integer := 0;
  v_resolved_payment text;
  v_clean_ad_unit_id text := nullif(trim(coalesce(p_ad_unit_id, '')), '');
  v_requested_payment text := lower(coalesce(nullif(trim(p_payment), ''), 'key'));
  cache_quality numeric := 0;
  skill_quality numeric := 0;
  rarity_value text;
  item_value bigint;
  item_level integer;
begin
  if actor is null then raise exception 'Authentication required'; end if;
  if nonce is null or length(trim(nonce)) < 8 then raise exception 'nonce is required'; end if;

  select result_payload into prior from public.verified_action_ledger where user_id = actor and idempotency_key = nonce;
  if prior is not null then return prior; end if;

  perform pg_advisory_xact_lock(hashtext(actor::text));

  select * into p from public.profiles where id = actor for update;
  if not found then raise exception 'Profile not found'; end if;

  -- Cache box lane (0037): the daily budget gate + free-first
  -- payment resolution (content owner: src/content/cacheLane.ts;
  -- resolveCacheBoxPayment is the TS statement of this logic).
  -- The cap is the cacheBoxDailyCap lever (0018 registry), read
  -- through cc_economy_config_number and clamped [1, 30] exactly
  -- like the registry and the content resolver. The openings table
  -- is the budget's record: counted inside this transaction, under
  -- the advisory lock taken above, so concurrent opens cannot
  -- race past the cap.
  v_daily_cap := least(30, greatest(1,
    public.cc_economy_config_number('cacheBoxDailyCap', 10)::integer));
  select coalesce(count(*) filter (where payment = 'free'), 0)::integer,
         coalesce(count(*) filter (where payment = 'ad'), 0)::integer,
         coalesce(count(*) filter (where payment = 'key'), 0)::integer,
         coalesce(count(*), 0)::integer
    into v_free_today, v_ad_today, v_key_today, v_opened_today
    from public.cache_box_openings
   where player_id = actor and open_day = v_open_day;
  if v_opened_today >= v_daily_cap then
    raise exception 'Daily cache box limit reached';
  end if;
  -- Free-first ordering: while the day's free opening remains, ANY
  -- request resolves to it — a key or an ad is never consumed for
  -- the free slot. After it, the player's chosen payment rules: an
  -- ad opening is attested by this call itself (client-attested,
  -- no SSV — the ad unit id is the claim, recorded on the opening
  -- row); a 'free' request with none left is refused.
  if v_free_today < 1 then
    v_resolved_payment := 'free';
  elsif v_requested_payment = 'ad' then
    if v_clean_ad_unit_id is null then raise exception 'ad_unit_id is required'; end if;
    v_resolved_payment := 'ad';
  elsif v_requested_payment = 'key' then
    v_resolved_payment := 'key';
  elsif v_requested_payment = 'free' then
    raise exception 'Free cache box already used today';
  else
    raise exception 'Unknown cache box payment';
  end if;
  if v_resolved_payment = 'key' and p.cache_tokens < 1 then
    raise exception 'Not enough tokens';
  end if;

  -- Cache quality (0031): the draw reads the TOTAL cache quality —
  -- the Scavenger node's cacheQuality effect (Encrypted Payloads,
  -- skill spends x node definitions; class-mod boosts do not feed
  -- the draw) PLUS the Cache Rank Cache Optimizer track. This is
  -- the first consumer of the cacheQuality effect (registry:
  -- src/lib/skills/skillConsumers.ts).
  select coalesce(sum((d.effects ->> 'cacheQuality')::numeric * s.points), 0)
    into skill_quality
    from (select key as node_id, (value)::numeric::integer as points
            from jsonb_each_text(coalesce(p.skill_spends, '{}'::jsonb))) s
    join public.skill_node_definitions d on d.id = s.node_id;
  cache_quality := greatest(0::numeric, coalesce(skill_quality, 0))
    + public.cc_cache_rank_bonus_fraction(p.cache_rank_spends, 'cacheQuality');
  odds := public.cc_draw_odds('cache_primary_rarity', cache_quality);
  rarity_value := odds ->> 'outcome';

  if v_resolved_payment = 'key' then
    update public.profiles set cache_tokens = cache_tokens - 1 where id = actor returning * into p;
  end if;

  item_level := greatest(1, p.player_level);
  item_value := public.cc_compute_item_estimated_value(
    jsonb_build_object('odds', odds),
    'weapon',
    rarity_value,
    item_level
  );

  insert into public.item_instances (
    owner_user_id,
    kind,
    item_level,
    rarity,
    estimated_value,
    supply_mode,
    payload
  ) values (
    actor,
    'weapon',
    item_level,
    rarity_value,
    item_value,
    'verified_action',
    public.cc_generate_weapon_payload(item_level, rarity_value)
  ) returning * into item;

  -- Record the opening (0037): the budget's audit row, written
  -- inside this transaction and after the nonce-prior return at the
  -- top, so a replayed nonce records nothing and grants nothing.
  insert into public.cache_box_openings (player_id, open_day, payment, ad_unit_id, item_id)
  values (actor, v_open_day, v_resolved_payment,
          case when v_resolved_payment = 'ad' then v_clean_ad_unit_id else null end,
          item.id);
  if v_resolved_payment = 'free' then v_free_today := v_free_today + 1;
  elsif v_resolved_payment = 'ad' then v_ad_today := v_ad_today + 1;
  else v_key_today := v_key_today + 1;
  end if;
  v_opened_today := v_opened_today + 1;

  result := jsonb_build_object('action_type', 'cc_make_item', 'profile', public.cc_profile_snapshot(p), 'odds', odds, 'cache_quality', cache_quality, 'item', to_jsonb(item),
    'payment', v_resolved_payment,
    'cache_lane', jsonb_build_object(
      'day', v_open_day,
      'cap', v_daily_cap,
      'free_per_day', 1,
      'opened_today', v_opened_today,
      'remaining', greatest(0, v_daily_cap - v_opened_today),
      'free_available', v_free_today < 1,
      'by_payment', jsonb_build_object('free', v_free_today, 'ad', v_ad_today, 'key', v_key_today)));

  insert into public.verified_action_ledger(user_id, action_type, idempotency_key, result_payload)
  values (actor, 'cc_make_item', nonce, result);

  return result;
end;
$function$;

