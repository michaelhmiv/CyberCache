-- =====================================================================
-- 0036 — Daily login streak: escalating ladder, day-7 key, tiered
-- cycles (content owner: src/content/loginStreak.ts).
--
-- A streak day is earned by the player's first authenticated
-- check-in of a UTC day, recorded server-side by
-- cc_record_login_streak_day (invoked from the observe-and-record
-- GET /api/login-streak/me — the Cache Rank pattern, 0031). The
-- day comes from the DATABASE clock; no request body names a day,
-- a streak length, or an amount.
--
-- Pieces:
--   1. login_streak_state — one standing row per player (current /
--      longest streak, last claimed day, last cycle position).
--   2. login_streak_claims — one row per (player, UTC day): the
--      EXACTLY-ONCE anchor (its primary key is the idempotency
--      key) and the profile fold's record — longest streak is
--      max(streak_length) over a player's claims, in the same
--      records-only style as migration 0034's lifetime fold.
--   3. login_streak_reward_definitions — the ladder, seeded for
--      tiers 1–5 × cycle days 1–7 and pinned row-for-row against
--      LOGIN_STREAK_REWARD_TABLE in src/content/loginStreak.ts
--      (vitest parity pins + the slice SQL harness).
--   4. cc_record_login_streak_day — the one grant path: streak
--      arithmetic, lever scalars via cc_economy_config_number
--      (0018), the profile credit/fragment/key application, the
--      claim + state writes, and the verified_action_ledger row
--      (action_type 'cc_login_streak_claim') the meters fold.
--   5. Economy meters: economy_metrics gains
--      credits_minted_login_streak (folded into
--      credits_minted_total — a real faucet),
--      cache_fragments_from_login_streak and
--      cache_keys_from_login_streak (own sources, distinct from
--      roaming fragments, leaderboard keys, and ad-lane issuance);
--      cc_compute_economy_metrics restated (0035 body + the three
--      folds).
--
-- Sizing (content module carries the full note): baseline roaming
-- pays ~15 credits/minute, so a tier-1 week (1,900 credits, 9
-- fragments, 1 key) is ≈2 hours of baseline roaming spread over 7
-- days. The key never scales with tier: ≤1 key/week/player, a
-- ceiling by construction. Guests earn identically — grants key
-- on the profile row, never on account state.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Standing streak state (one row per player, created lazily by
--    the grant function on first check-in).
-- ---------------------------------------------------------------------
create table if not exists public.login_streak_state (
  player_id uuid primary key references public.profiles(id) on delete cascade,
  current_streak integer not null default 0 check (current_streak >= 0),
  longest_streak integer not null default 0 check (longest_streak >= 0),
  last_claim_day date,
  last_cycle_day integer check (last_cycle_day is null or (last_cycle_day >= 1 and last_cycle_day <= 7)),
  last_tier integer check (last_tier is null or (last_tier >= 1 and last_tier <= 5)),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. Claim rows: exactly one per player per UTC day. The grant
--    amounts actually paid are stamped on the row (post-lever), so
--    the row is the audit record as well as the anchor.
-- ---------------------------------------------------------------------
create table if not exists public.login_streak_claims (
  player_id uuid not null references public.profiles(id) on delete cascade,
  claim_day date not null,
  streak_length integer not null check (streak_length >= 1),
  cycle_day integer not null check (cycle_day >= 1 and cycle_day <= 7),
  tier integer not null check (tier >= 1 and tier <= 5),
  credits_awarded bigint not null default 0 check (credits_awarded >= 0),
  fragments_awarded bigint not null default 0 check (fragments_awarded >= 0),
  cache_keys_awarded integer not null default 0 check (cache_keys_awarded >= 0),
  claimed_at timestamptz not null default now(),
  primary key (player_id, claim_day)
);

-- ---------------------------------------------------------------------
