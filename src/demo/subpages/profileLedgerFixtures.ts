/** A's spend plan: Gunslinger 8 · Demolition 5 · Scavenger 5 = 18 of
 *  23 points at Level 24 — 5 unspent. */
function fixtureSkillSpends(): Record<string, number> {
  const spent: Record<string, number> = {};
  const fill = (tree: SkillTreeType, budget: number) => {
    const nodes = [...getSkillTreeNodes(tree)].sort((a, b) => a.tier - b.tier || a.index - b.index);
    let remaining = budget;
    for (const node of nodes) {
      if (remaining <= 0) break;
      const add = Math.min(node.maxPoints, remaining);
      if (add > 0) {
        spent[node.id] = add;
        remaining -= add;
      }
    }
  };
  fill(SkillTreeType.Gunslinger, 8);
  fill(SkillTreeType.Demolition, 5);
  fill(SkillTreeType.Scavenger, 5);
  return spent;
}
